import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'vite';

test('traveler requests reach the guide and keep the agreed price split through completion', async () => {
  const values = new Map();
  globalThis.localStorage = { getItem: (key) => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
  const vite = await createServer({ server: { middlewareMode: true, hmr: false }, appType: 'custom', logLevel: 'silent' });
  try {
    const guideRepo = await vite.ssrLoadModule('/src/features/guides/repository.js');
    const guideViews = await vite.ssrLoadModule('/src/features/guides/view.js');
    const date = new Date(Date.now() + 86400000).toISOString().slice(0, 10);
    const nextDate = new Date(Date.now() + 2 * 86400000).toISOString().slice(0, 10);
    const { activeGuide, availableGuides, createGuideRequest, decideGuidePrice, financeBreakdown, financeDashboardView, guideDemoData, markGuideRequestPaid, packagePrice, priceSplit, proposeGuidePrice, publicPackagePrice, releaseGuidePayout, reviewGuideRequest, toggleGuideDate, toggleGuideExperience, updateGuideRequest } = { ...guideRepo, financeDashboardView: guideViews.financeDashboardView };
    const option = (await vite.ssrLoadModule('/src/features/experiences/data.js')).getExperience('arena').packageOptions[0];
    assert.deepEqual(priceSplit(2500000), { travelerTotal: 2500000, guideShare: 2250000, platformShare: 250000 });
    assert.deepEqual(financeBreakdown(2500000), { schemaVersion: 1, travelerTotal: 2500000, guideShare: 2250000, platformShare: 250000, paymentFee: 75000, platformNet: 175000 });
    assert.equal(proposeGuidePrice('guide-adi', 'rinjani-2d1n', 2500000), true);
    assert.match(guideViews.guidePriceApprovalsView(), /Guide proposes/);
    assert.equal(packagePrice(activeGuide(), option), option.price);
    assert.equal(publicPackagePrice('arena', option), option.price);
    assert.equal(decideGuidePrice('guide-adi', 'rinjani-2d1n', 'approved'), true);
    assert.equal(packagePrice(activeGuide(), option), 2500000);
    assert.equal(proposeGuidePrice('guide-adi', 'rinjani-2d1n', 2700000), true);
    assert.equal(decideGuidePrice('guide-adi', 'rinjani-2d1n', 'rejected'), true);
    assert.equal(packagePrice(activeGuide(), option), 2500000);
    assert.equal(availableGuides('arena', 'rinjani-2d1n', date, 1)[0].id, 'guide-adi');
    assert.equal(createGuideRequest({ experienceId: 'arena', packageId: 'rinjani-2d1n', guideId: 'guide-adi', date, time: '5:00 AM', adults: 1, children: 0, travelerName: 'Traveler Demo', travelerEmail: 'traveler@example.com', expectedUnitPrice: 2600000 }), null);
    const request = createGuideRequest({ experienceId: 'arena', packageId: 'rinjani-2d1n', guideId: 'guide-adi', date, time: '5:00 AM', adults: 1, children: 0, travelerName: 'Traveler Demo', travelerEmail: 'traveler@example.com', expectedUnitPrice: 2500000 });
    assert.equal(request.status, 'pending');
    assert.equal(request.unitPrice, 2500000);
    assert.equal(request.guideShare, 2250000);
    assert.equal(request.platformShare, 250000);
    assert.equal(request.finance.paymentFee, 75000);
    assert.equal(request.finance.platformNet, 175000);
    assert.equal(request.priceApprovedBy, 'demo-admin');
    assert.equal(proposeGuidePrice('guide-adi', 'rinjani-2d1n', 2800000), true);
    assert.equal(decideGuidePrice('guide-adi', 'rinjani-2d1n', 'approved'), true);
    assert.equal(guideDemoData().requests[0].unitPrice, 2500000);
    assert.equal(createGuideRequest({ experienceId: 'arena', packageId: 'rinjani-2d1n', guideId: 'guide-adi', date, adults: 1, children: 0, travelerName: 'Traveler Demo', travelerEmail: 'traveler@example.com', expectedUnitPrice: 2500000 }), null);
    assert.match(guideViews.guideDashboardView(), /Traveler Demo/);
    assert.match(guideViews.guideDashboardView(), /Total booking/);
    assert.equal(updateGuideRequest(request.id, 'guide-adi', 'accepted'), true);
    assert.equal(markGuideRequestPaid(request.id, 'traveler@example.com'), true);
    assert.equal(guideDemoData().requests[0].paymentStatus, 'paid');
    assert.equal(availableGuides('arena', 'rinjani-2d1n', date, activeGuide().capacity).length, 0);
    assert.equal(toggleGuideDate('guide-adi', date), false);
    assert.equal(toggleGuideDate('guide-adi', nextDate), false);
    assert.equal(availableGuides('arena', 'rinjani-2d1n', nextDate, activeGuide().capacity).length, 0);
    assert.equal(updateGuideRequest(request.id, 'guide-adi', 'declined'), false);
    assert.equal(updateGuideRequest(request.id, 'guide-adi', 'completed'), true);
    assert.equal(guideDemoData().requests[0].payoutStatus, 'pending');
    assert.equal(releaseGuidePayout(request.id), true);
    assert.equal(guideDemoData().requests[0].payoutStatus, 'paid');
    assert.match(financeDashboardView(), /Platform net est\./);
    assert.equal(reviewGuideRequest(request.id, 'traveler@example.com', 5, 'Great trek'), true);
    assert.equal(reviewGuideRequest(request.id, 'traveler@example.com', 5, 'Again'), false);
    assert.equal(guideDemoData().requests[0].review.comment, 'Great trek');
    assert.equal(toggleGuideExperience('guide-adi', 'vatican'), true);
    const waterfallOption = (await vite.ssrLoadModule('/src/features/experiences/data.js')).getExperience('vatican').packageOptions[0];
    assert.equal(availableGuides('vatican', waterfallOption.id, date, 1).some((guide) => guide.id === 'guide-adi'), false);
    assert.equal(proposeGuidePrice('guide-adi', waterfallOption.id, 500000), true);
    assert.equal(availableGuides('vatican', waterfallOption.id, date, 1).some((guide) => guide.id === 'guide-adi'), false);
    assert.equal(decideGuidePrice('guide-adi', waterfallOption.id, 'approved'), true);
    assert.equal(availableGuides('vatican', waterfallOption.id, date, 1).some((guide) => guide.id === 'guide-adi'), true);
    const legacy = guideDemoData();
    delete legacy.guides[0].priceAgreements;
    legacy.guides[0].prices = { 'rinjani-2d1n': 9999999 };
    values.set('lombok-guide-demo-v1', JSON.stringify(legacy));
    const migrated = guideDemoData().guides[0];
    assert.equal(packagePrice(migrated, option), option.price);
    assert.equal(migrated.priceAgreements['rinjani-2d1n'].proposal.amount, 9999999);
    assert.equal(migrated.priceAgreements['rinjani-2d1n'].proposal.status, 'pending');
  } finally { await vite.close(); delete globalThis.localStorage; }
});
